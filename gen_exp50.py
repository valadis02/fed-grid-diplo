#!/usr/bin/env python3
"""
50-node setup: 2 laptops x 25 edges, 2 RPi fogs, cloud on laptop A.
Same images / env vars as the 10- and 25-edge Docker setup; only hosts/ports change.

  gen : python gen_exp50.py gen --ip-a 192.168.1.4 --pi1 <pi51> --pi2 <pi52> --root-b C:/fed [--data lcl50_diverse]
  Data (default): lcl50_diverse/house_1..50 (make_lcl_data50_v2.py --select stratified)
  --mode dayahead (default): πρόβλεψη επόμενης μέρας στις 00:00 (48 μισάωρα), train Νοε 2012–Οκτ 2013,
                             eval Νοε 2013–Ιαν 2014 (βλ. shared/forecasting.py)
  --mode legacy            : παλιά ρύθμιση (lcl_data50, 2012-02-01, 274+92 μέρες)
  prep: python gen_exp50.py prep --root <repo> --start 1 --end 50   (only creates edge/models/node_i)
"""
import argparse
import os
import shutil

P = "n50_"
DATA = "lcl50_diverse"

# (FORECAST_MODE, TRAINING_DATE, TRAIN_DAYS, EVAL_DAYS, BATCH_SIZE)
MODES = {
    "dayahead": ("dayahead", "2012-10-15", 382, 92, 64),   # train [2012-10-15, 2013-11-01), eval 2013-11-01..2014-01-31
    "legacy":   ("legacy",   "2012-02-01", 274, 92, 32),
}
M = MODES["dayahead"]

# Byzantine ρυθμίσεις (βλ. cmd_gen). ATTACKERS: οι 15/50 (30%) επιτιθέμενοι του Byzantine πειράματος 1
# (7 στο fog1 + 8 στο fog2, ίδια ανάθεση με την offline προσομοίωση).
ATTACKERS_30 = [2, 3, 5, 10, 12, 15, 17, 29, 30, 33, 39, 40, 42, 44, 50]
ATK = dict(attack="none", attackers=[], zeta=2.6, sigma=30.0)
FOGCFG = dict(strategy="fedavg", krum_f=8, kappa=0.5, epochs=5)


def mode_env(indent="      "):
    fm, td, tr, ev, bs = M
    return "\n".join(indent + x for x in [f"- FORECAST_MODE={fm}", f"- TRAINING_DATE={td}",
                                           f"- TRAIN_DAYS={tr}", f"- EVAL_DAYS={ev}", f"- BATCH_SIZE={bs}"])

HEAD = """# Auto-generated by gen_exp50.py
networks:
  aqtf_shared_network:
    external: true

services:
"""


def edge_block(i, fog_ip, root, rounds, epochs):
    return f"""
  edge_node_{i}:
    image: edge-node:latest
    container_name: {P}edge_{i}
    environment:
      - FOG_RABBITMQ_HOST={fog_ip}
      - FOG_MQTT_HOST={fog_ip}
      - FOG_MQTT_PORT=1883
      - EDGE_NAME=edge_node_{i}
      - MAX_ROUNDS={rounds + 2}
      - WAIT_TIMEOUT_SECS=14400
      - TF_CPP_MIN_LOG_LEVEL=2
      - TF_ENABLE_ONEDNN_OPTS=0
{mode_env()}
      - EPOCHS={epochs}
      - ATTACK_TYPE={ATK["attack"] if i in ATK["attackers"] else "none"}
      - ATTACK_ZETA={ATK["zeta"]}
      - ATTACK_NOISE_SCALE={ATK["sigma"]}
      - NORMALIZATION=per_house
      - MODEL_INIT_SEED=42
    networks: [aqtf_shared_network]
    command: python3 -m edge.model.run_federated_cycle
    volumes:
      - {root}/{DATA}/house_{i}:/app/edge/data
      - {root}/edge/models/node_{i}:/app/edge/models
    restart: on-failure
"""


def cloud_yml(root_a, n_fogs):
    fog_names = ",".join(f"FOG_NODE_{k}" for k in range(1, n_fogs + 1))
    return HEAD + f"""
  cloud_app:
    image: cloud_node_app:latest
    container_name: {P}cloud_app
    environment:
      - RABBITMQ_HOST={P}rabbitmq_cloud
      - CLOUD_RABBITMQ_HOST={P}rabbitmq_cloud
      - CLOUD_MQTT_HOST={P}mqtt_cloud
      - CLOUD_MQTT_PORT=1883
      - APP_HOST_PORT=8081
      - FOG_NAMES={fog_names}
      - FALLBACK_FOG_NAMES={fog_names}
      - NUM_FOG_NODES={n_fogs}
{mode_env()}
      - NORMALIZATION=per_house
      - FOG_GROUPS=1-25,26-50
    ports:
      - "8082:8081"
    depends_on:
      - {P}rabbitmq_cloud
      - {P}mqtt_cloud
    networks:
      - aqtf_shared_network
    command: python3 -m cloud.communication.cloud_messaging
    volumes:
      - {root_a}/cloud/models:/app/models
      - {root_a}/cloud/status:/app/status
      - {root_a}/{DATA}:/app/data:ro
    restart: on-failure

  {P}rabbitmq_cloud:
    image: rabbitmq:3-management
    container_name: {P}rabbitmq_cloud
    ports:
      - "5673:5672"
      - "15673:15672"
    networks:
      - aqtf_shared_network

  {P}mqtt_cloud:
    image: eclipse-mosquitto
    container_name: {P}mqtt_cloud
    ports:
      - "1884:1883"
    networks:
      - aqtf_shared_network
    volumes:
      - {root_a}/cloud/mosquitto.conf:/mosquitto/config/mosquitto.conf
"""


def fog_yml(k, root_pi, ip_a, edge_names):
    strat = FOGCFG["strategy"]
    return HEAD + f"""
  {P}rabbitmq_fog:
    image: rabbitmq:3-management
    container_name: {P}rabbitmq_fog
    ports:
      - "5672:5672"
      - "15672:15672"
    networks:
      - aqtf_shared_network

  {P}mqtt_fog:
    image: eclipse-mosquitto
    container_name: {P}mqtt_fog
    ports:
      - "1883:1883"
    networks:
      - aqtf_shared_network
    volumes:
      - {root_pi}/fog/mosquitto.conf:/mosquitto/config/mosquitto.conf

  fog_app:
    image: fog_node_app:latest
    container_name: {P}fog_app
    environment:
      - FOG_RABBITMQ_HOST={P}rabbitmq_fog
      - CLOUD_RABBITMQ_HOST={ip_a}
      - CLOUD_RABBITMQ_PORT=5673
      - FOG_MQTT_HOST={P}mqtt_fog
      - FOG_MQTT_PORT=1883
      - CLOUD_MQTT_HOST={ip_a}
      - CLOUD_MQTT_PORT=1884
      - FOG_NAME=FOG_NODE_{k}
      - EDGE_NAMES={",".join(edge_names)}
      - ENCRYPTION_MODE=none
      - AGGREGATION_STRATEGY={strat}
      - FEDAVG_WEIGHTING=uniform
      - KRUM_NUM_BYZANTINE={FOGCFG["krum_f"]}
      - FEDCONSENSUS_KAPPA={FOGCFG["kappa"]}
      - FLTRUST_ROOT_DATA_PATH=/app/fltrust_root/input_data.csv
      - FLTRUST_EPOCHS={FOGCFG["epochs"]}
      - MODEL_INIT_SEED=42
      - NORMALIZATION=per_house
{mode_env()}
    ports:
      - "8084:8081"
    depends_on:
      - {P}rabbitmq_fog
      - {P}mqtt_fog
    networks:
      - aqtf_shared_network
    command: uvicorn fog.communication.app_factory:app --host 0.0.0.0 --port 8081
    volumes:
      - {root_pi}/fog/models:/app/models
      - {root_pi}/fog/models/outbox:/app/models/outbox
      - {root_pi}/fltrust_root:/app/fltrust_root:ro
    restart: on-failure
"""


def cmd_gen(a):
    global DATA, M
    DATA, M = a.data, MODES[a.mode]
    ATK.update(attack=a.attack, zeta=a.zeta, sigma=a.sigma,
               attackers=([] if a.attack == "none" else
                          ATTACKERS_30 if a.attackers == "30" else [int(x) for x in a.attackers.split(",") if x]))
    FOGCFG.update(strategy=a.strategy, krum_f=a.krum_f, kappa=a.kappa, epochs=a.epochs)
    print(f"mode={a.mode} data={DATA} env={M}")
    print(f"strategy={a.strategy} attack={a.attack} attackers={ATK['attackers']} zeta={a.zeta} sigma={a.sigma} krum_f={a.krum_f}")
    os.makedirs(a.out, exist_ok=True)
    n = a.edges_per_laptop
    ids_a = list(range(1, n + 1))
    ids_b = list(range(n + 1, 2 * n + 1))

    def w(name, text):
        with open(os.path.join(a.out, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", name)

    w("exp50_cloud_A.yml", cloud_yml(a.root_a, 2))
    w("exp50_fog1_pi.yml", fog_yml(1, a.root_pi1, a.ip_a, [f"edge_node_{i}" for i in ids_a]))
    w("exp50_fog2_pi.yml", fog_yml(2, a.root_pi2, a.ip_a, [f"edge_node_{i}" for i in ids_b]))
    w("exp50_edges_A.yml", HEAD + "".join(edge_block(i, a.pi1, a.root_a, a.rounds, a.epochs) for i in ids_a))
    w("exp50_edges_B.yml", HEAD + "".join(edge_block(i, a.pi2, a.root_b, a.rounds, a.epochs) for i in ids_b))


def cmd_prep(a):
    global DATA
    DATA = a.data
    for i in range(a.start, a.end + 1):
        if not os.path.isdir(os.path.join(a.root, DATA, f"house_{i}")):
            print(f"WARNING: missing {DATA}/house_{i}")
        os.makedirs(os.path.join(a.root, "edge", "models", f"node_{i}"), exist_ok=True)
    print("prep done")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)

    g = sp.add_parser("gen")
    g.add_argument("--ip-a", required=True, help="IP of laptop A (cloud)")
    g.add_argument("--pi1", required=True, help="IP of raspberrypi51 (FOG_NODE_1)")
    g.add_argument("--pi2", required=True, help="IP of raspberrypi52 (FOG_NODE_2)")
    g.add_argument("--root-a", default="C:/Users/balt5/fed-grid-diplo")
    g.add_argument("--root-b", default="C:/fed", help="repo path on laptop B")
    g.add_argument("--root-pi1", default="/home/raspberrypi51/fed")
    g.add_argument("--root-pi2", default="/home/raspberrypi52/fed")
    g.add_argument("--rounds", type=int, default=10)
    g.add_argument("--epochs", type=int, default=5)
    g.add_argument("--edges-per-laptop", type=int, default=25)
    g.add_argument("--out", default="exp50")
    g.add_argument("--data", default=DATA, help="φάκελος δεδομένων (lcl50_diverse | lcl50_similar | lcl_data50)")
    g.add_argument("--mode", choices=list(MODES), default="dayahead")
    g.add_argument("--strategy", default="fedavg",
                   choices=["fedavg", "krum", "multi_krum", "tmean", "fltrust2", "fedconsensus", "fedconsensus_v2", "fedconsensus_sv"])
    g.add_argument("--attack", default="none",
                   choices=["none", "label_flipping", "sign_flipping", "sign_flipping_weights", "gaussian_noise"])
    g.add_argument("--attackers", default="30", help='"30" = οι 15 προκαθορισμένοι (30%%) ή λίστα π.χ. "2,3,5"')
    g.add_argument("--zeta", type=float, default=2.6, help="sign_flipping: g -> -zeta*g")
    g.add_argument("--sigma", type=float, default=30.0, help="gaussian_noise: g + N(0, sigma^2)")
    g.add_argument("--krum-f", type=int, default=8, help="Krum f ανά fog (25 edges)")
    g.add_argument("--kappa", type=float, default=0.5, help="FedConsensus-v2 kappa")
    g.set_defaults(fn=cmd_gen)

    p = sp.add_parser("prep")
    p.add_argument("--root", required=True)
    p.add_argument("--start", type=int, required=True)
    p.add_argument("--end", type=int, required=True)
    p.add_argument("--data", default=DATA)
    p.set_defaults(fn=cmd_prep)

    args = ap.parse_args()
    args.fn(args)

    